import {beforeAll,afterAll,it,expect,vi} from 'vitest';
import {and,eq} from 'drizzle-orm';
import {randomUUID} from 'node:crypto';
vi.mock('../scripts/preview-guard',()=>({assertHostedPreviewSeedAllowed:vi.fn()}));
import {seedDemo,refreshHostedPreviewRoles} from '../src/server/seed';
import {retireSyntheticAccess} from '../src/server/retire-synthetic-access';
import {getDb,closeDb} from '../src/server/db';
import {getAuth} from '../src/server/auth';
import {getAccess,grantAccess,deleteAccess,renameAccessMember,assertEmailAccess} from '../src/server/access';
import {getWorkspace,principalFor} from '../src/server/service';
import {getRhythm} from '../src/server/rhythm';
import * as s from '../src/server/schema';
import type {Principal} from '../src/server/policy';
let owner:Principal,realId:string,sampleId:string;
const realEmail='real-manager@example.com';
beforeAll(async()=>{
 process.env.DEMO_MODE='true';process.env.PGLITE_DATA_DIR='memory://';delete process.env.DATABASE_URL;delete process.env.VERCEL;
 process.env.BETTER_AUTH_URL='http://localhost:3000';process.env.BETTER_AUTH_SECRET='retirement-isolated-secret-12345678901234567890';process.env.DEMO_PASSWORD='retirement-password-12345';process.env.DEMO_EMAIL='demo@samgad.example';
 await seedDemo();const db=await getDb();const [u]=await db.select().from(s.user).where(eq(s.user.email,'demo@samgad.example'));owner=await principalFor(u.id,u.name);
 await grantAccess(owner,{email:realEmail,name:'מנהל אמיתי',level:'all',password:'real-manager-password-12345'});
 realId=(await getAccess(owner)).members.find(m=>m.email===realEmail)!.id;
 sampleId=(await getAccess(owner)).members.find(m=>m.email==='company.b@samgad.example')!.id;
},60000);
afterAll(closeDb);
it('never re-creates deleted fixture access or overwrites edited names when initialization runs again',async()=>{
 const db=await getDb();const sample=(await getAccess(owner)).members.find(m=>m.email==='company.a@samgad.example')!;
 await renameAccessMember(owner,{userId:owner.userId,name:'איתמר — שם שנערך'});
 await deleteAccess(owner,{userId:sample.id});
 await seedDemo();await seedDemo();
 expect((await getAccess(owner)).members.some(m=>m.id===sample.id)).toBe(false);
 expect((await db.select().from(s.user).where(eq(s.user.id,owner.userId)))[0].name).toBe('איתמר — שם שנערך');
 expect((await getAccess(owner)).members.find(m=>m.id===realId)?.name).toBe('מנהל אמיתי');
 expect((await db.select().from(s.tasks)).some(t=>t.ownerId===sample.id)).toBe(true);
});
it('removes only original sample memberships during cleanup, preserving real users, work and other workspaces',async()=>{
 const db=await getDb();
 await grantAccess(owner,{email:'company.b@samgad.example',level:'own'});
 await (await getAuth()).api.signInEmail({body:{email:'company.b@samgad.example',password:process.env.DEMO_PASSWORD!}});
 await db.insert(s.rhythmGroups).values({id:'retirement-mixed-group',organizationId:owner.organizationId,creatorId:owner.userId,name:'קבוצה מעורבת',emails:['company.b@samgad.example',realEmail]});
 const [sample]=await db.select().from(s.user).where(eq(s.user.id,sampleId));
 await db.insert(s.organizations).values({id:'other-workspace',name:'other workspace'});
 await db.insert(s.memberships).values({id:randomUUID(),organizationId:'other-workspace',userId:sampleId,role:'viewer'});
 const tasksBefore=await db.select().from(s.tasks),decisionsBefore=await db.select().from(s.decisions);
 expect((await retireSyntheticAccess(owner.organizationId)).retired).toBe(8);
 const members=(await getAccess(owner)).members;
 expect(members.map(m=>m.email).sort()).toEqual(['demo@samgad.example',realEmail].sort());
 expect(members.find(m=>m.id===realId)).toMatchObject({name:'מנהל אמיתי',level:'all',active:true});
 expect((await db.select().from(s.tasks))).toEqual(tasksBefore);expect((await db.select().from(s.decisions))).toEqual(decisionsBefore);
 expect((await db.select().from(s.user).where(eq(s.user.id,sampleId)))[0]).toEqual(sample);
 expect((await db.select().from(s.memberships).where(and(eq(s.memberships.userId,sampleId),eq(s.memberships.organizationId,'other-workspace'))))).toHaveLength(1);
 expect((await db.select().from(s.session).where(eq(s.session.userId,sampleId)))).toHaveLength(0);
 expect((await db.select().from(s.workspaceAccessGrants).where(eq(s.workspaceAccessGrants.userId,sampleId)))).toHaveLength(0);
 expect((await db.select().from(s.rhythmGroups).where(eq(s.rhythmGroups.id,'retirement-mixed-group')))[0].emails).toEqual([realEmail]);
 expect((await getWorkspace(owner)).users.map(u=>u.id).sort()).toEqual([owner.userId,realId].sort());
 await expect(assertEmailAccess('company.c@samgad.example')).rejects.toMatchObject({status:403});
 await db.delete(s.memberships).where(eq(s.memberships.organizationId,'other-workspace'));
 await db.delete(s.organizations).where(eq(s.organizations.id,'other-workspace'));
});
it('keeps deleted real accounts and sample accounts deleted across repeated refreshes and role synchronization',async()=>{
 await deleteAccess(owner,{userId:realId});
 expect((await refreshHostedPreviewRoles()).retired).toBe(0);
 await seedDemo();await getRhythm(owner);await getWorkspace(owner);await getRhythm(owner);
 expect((await refreshHostedPreviewRoles()).retired).toBe(0);
 expect((await getAccess(owner)).members.map(m=>m.id)).toEqual([owner.userId]);
 expect((await getWorkspace(owner)).users.map(u=>u.id)).toEqual([owner.userId]);
 await expect(assertEmailAccess(realEmail)).rejects.toMatchObject({status:403});
 await expect(principalFor(realId,'removed manager')).rejects.toMatchObject({status:403});
});
