import {beforeAll,afterAll,it,expect,vi} from 'vitest';
import {eq} from 'drizzle-orm';
import {getDb,closeDb} from '../src/server/db';
import {seedDemo} from '../src/server/seed';
import {principalFor,getWorkspace} from '../src/server/service';
import {grantAccess} from '../src/server/access';
import {getRhythm,saveRhythmGroup,createRhythmItem} from '../src/server/rhythm';
import {workspaceSchedule,seal} from '../src/server/google-calendar';
import {createHash,randomUUID} from 'node:crypto';
import * as s from '../src/server/schema';
import type {Principal} from '../src/server/policy';
let owner:Principal,a:Principal,b:Principal;
beforeAll(async()=>{
 process.env.DEMO_MODE='true';process.env.PGLITE_DATA_DIR='memory://';delete process.env.DATABASE_URL;delete process.env.VERCEL;
 process.env.BETTER_AUTH_URL='http://localhost:3000';process.env.BETTER_AUTH_SECRET='weekly-schedule-isolated-secret-1234567890';process.env.DEMO_PASSWORD='weekly-schedule-password-12345';process.env.DEMO_EMAIL='demo@samgad.example';
 await seedDemo();const users=await(await getDb()).select().from(s.user);
 const p=(email:string)=>{const u=users.find(u=>u.email===email)!;return principalFor(u.id,u.name);};
 owner=await p('demo@samgad.example');a=await p('company.a@samgad.example');b=await p('company.b@samgad.example');
},60000);
afterAll(async()=>{vi.unstubAllGlobals();await closeDb();});
it('keeps pickers synchronized with explicit grants and derives collection membership',async()=>{
 expect((await getWorkspace(owner)).users.map(u=>u.id)).toEqual([owner.userId]);
 await grantAccess(owner,{email:'company.a@samgad.example',level:'own'});
 await grantAccess(owner,{email:'company.b@samgad.example',level:'own'});
 const data=await getRhythm(owner);
 expect(data.people.map(u=>u.id).sort()).toEqual([owner.userId,a.userId,b.userId].sort());
 const slot=data.groups.find(g=>g.name==='סמ״פ א׳')!;
 await (await getDb()).update(s.rhythmGroups).set({emails:[]}).where(eq(s.rhythmGroups.id,slot.id));
 expect((await getRhythm(owner)).groups.find(g=>g.id===slot.id)?.emails).toEqual(['company.a@samgad.example']);
 const group=data.groups.find(g=>g.name==='סמ״פים (קבוצה)')!;
 expect(group.emails.sort()).toEqual(['company.a@samgad.example','company.b@samgad.example']);
 const item=await createRhythmItem(owner,{clientRequestId:randomUUID(),title:'collective task',groupIds:[group.id]});
 expect(item.assigneeIds.sort()).toEqual([a.userId,b.userId].sort());
 await grantAccess(owner,{email:'company.b@samgad.example',level:'revoke'});
 expect((await getWorkspace(owner)).users.some(u=>u.id===b.userId)).toBe(false);
 expect((await getRhythm(owner)).groups.find(g=>g.id===group.id)?.emails).toEqual(['company.a@samgad.example']);
});
it('reads the shared calendar and expands collective titles without leaking other roles to deputies',async()=>{
 const db=await getDb();const groups=(await getRhythm(owner)).groups;
 const staff=groups.find(g=>g.name==='סקשר״גית')!;
 await saveRhythmGroup(owner,{name:staff.name,emails:['company.a@samgad.example'],version:staff.version},staff.id);
 const id=createHash('sha256').update(`${owner.organizationId}:${owner.userId}`).digest('hex');
 await db.insert(s.calendarConnections).values({id,userId:owner.userId,organizationId:owner.organizationId,encryptedTokens:seal({access_token:'test-token',expiresAt:Date.now()+3600000,scheduleCalendarId:'shared-test'})});
 const event=(id:string,summary:string)=>({id,summary,start:{dateTime:new Date().toISOString()},end:{dateTime:new Date(Date.now()+3600000).toISOString()}});
 const fetchMock=vi.fn(async(_input:string|URL)=>new Response(JSON.stringify({items:[event('a','שיחה סמ״פ א׳'),event('b','שיחה סמ״פ ב׳'),event('all','דיון סמ״פים'),event('staff','מטה 2'),event('prefix','סמ״פ אב'),{...event('cancelled','סמ״פים'),status:'cancelled'}]}),{status:200}));vi.stubGlobal('fetch',fetchMock);
 const mine=await workspaceSchedule(a);
 expect(mine.events.map(e=>e.id)).toEqual(['a','all','staff']);
 expect(mine.events.every(e=>!('groupIds' in e))).toBe(true);
 const full=await workspaceSchedule(owner);
 expect(full.events.find(e=>e.id==='all')?.groupIds).toContain(groups.find(g=>g.name==='סמ״פ א׳')!.id);
 expect(full.events.find(e=>e.id==='staff')?.groupIds).toContain(staff.id);
 expect(String(fetchMock.mock.calls[0]?.[0])).toContain('shared-test');
});
