import { expect, test } from '@playwright/test';
import { signInThroughForm } from './login';

test('offline create survives a full reload and automatically syncs once with persistent sign-in', async ({ page, context }) => {
  await signInThroughForm(page);
  await page.goto('/?view=personal');
  await expect(page.getByLabel('מצב סנכרון')).toContainText('מוכן לפתיחה אופליין');
  await page.locator(".task-filter-details > summary").click();
  await expect(page.getByLabel('סינון', {exact:true})).toBeVisible();
  const title = `אופליין ${Date.now()}`;
  await context.setOffline(true);
  await page.getByRole('button',{name:'הוספת משימה',exact:true}).click();
  const dialog=page.getByRole('dialog',{name:'משימה',exact:true});
  await dialog.getByLabel('שם המשימה').fill(title);
  await dialog.getByRole('button',{name:'שמירת המשימה',exact:true}).click();
  await expect(dialog).not.toBeVisible();
  await expect(page.getByLabel('מצב סנכרון')).toContainText('1 שינויים ממתינים');
  await expect(page.locator('.rhythm-card-list')).toContainText(title);
  await page.reload();
  await expect(page.locator('.rhythm-card-list')).toContainText(title);
  await expect(page.getByLabel('מצב סנכרון')).toContainText('1 שינויים ממתינים');
  if (!await page.getByLabel("סינון", {exact:true}).isVisible()) await page.locator(".task-filter-details > summary").click();
  await page.getByLabel('סינון',{exact:true}).selectOption('all');
  await page.locator('.rhythm-task-card').filter({hasText:title}).getByRole('button',{name:/^בוצע:/}).click();
  await expect(page.getByLabel('מצב סנכרון')).toContainText('2 שינויים ממתינים');
  await context.setOffline(false);
  await expect(page.getByLabel('מצב סנכרון')).toContainText('מסונכרן');
  await expect(page.getByLabel('מצב סנכרון')).not.toContainText('ממתינים');
  const data=await (await page.request.get('/api/rhythm')).json();
  const items=data.items.filter((r:{title:string})=>r.title===title);
  expect(items).toHaveLength(1);
  if (!await page.getByLabel("סינון", {exact:true}).isVisible()) await page.locator(".task-filter-details > summary").click();
  await page.getByLabel('סינון',{exact:true}).selectOption('all');
  const row=page.locator('.rhythm-task-card').filter({hasText:title});
  await context.setOffline(true);
  await row.getByRole('button',{name:/^לא בוצע:/}).click();
  await expect(page.getByLabel('מצב סנכרון')).toContainText('1 שינויים ממתינים');
  await page.reload();
  if (!await page.getByLabel("סינון", {exact:true}).isVisible()) await page.locator(".task-filter-details > summary").click();
  await page.getByLabel('סינון',{exact:true}).selectOption('all');
  await expect(page.getByLabel('מצב סנכרון')).toContainText('1 שינויים ממתינים');
  await context.setOffline(false);
  await expect(page.getByLabel('מצב סנכרון')).not.toContainText('ממתינים');
  const after=await (await page.request.get('/api/rhythm')).json();
  expect(after.occurrences.find((r:{itemId:string})=>r.itemId===items[0].id).done).toBe(false);
  const cookies=await context.cookies();
  expect(cookies.find(c=>c.name.includes('session_token'))!.expires).toBeGreaterThan(Date.now()/1000+27*86400);
});
